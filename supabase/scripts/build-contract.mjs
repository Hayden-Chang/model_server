import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const keywords = new Set(['$schema','$id','$defs','$ref','type','properties','required','additionalProperties',
  'minProperties','maxProperties','items','minItems','maxItems','uniqueItems','minimum','maximum',
  'minLength','maxLength','pattern','format','const','enum','anyOf','oneOf','description']);
function checkContract(schema, document) {
  for (const key of Object.keys(schema)) if (!keywords.has(key)) throw new Error('Unsupported SQL validator keyword: '+key);
  if (schema.$ref && (!schema.$ref.startsWith('#/$defs/') || !document.$defs[schema.$ref.slice(8)])) throw new Error('Unresolved schema reference');
  if (schema.format && !['date','date-time'].includes(schema.format)) throw new Error('Unsupported SQL validator format');
  for (const map of [schema.properties,schema.$defs]) for (const child of Object.values(map ?? {})) checkContract(child,document);
  for (const child of [schema.items,schema.additionalProperties]) if (child && typeof child==='object') checkContract(child,document);
  for (const child of [...schema.anyOf??[],...schema.oneOf??[]]) checkContract(child,document);
}
// v1 keeps its original applied migration. Each version dir emits only its newest
// revision, under versioned contract names; earlier revisions of that dir stay in
// their already applied migration files and are frozen history that this list no
// longer names (for example 202609110009_contract_v2.sql, superseded by
// 202609170018_contract_v2_puzzle_optional.sql). Applied files are never rewritten.
// `onConflict` emits an idempotent re-registration: row absent inserts, row present
// updates, so the same file is correct on a fresh database and on a deployed one.
const versions = [
  { dir: 'v1', output: '202609080001_contract.sql', suffix: '', prologue:
      'create schema if not exists sync_private;\n'
    + 'revoke all on schema sync_private from public, anon, authenticated;\n'
    + 'create table sync_private.contracts (name text primary key, schema jsonb not null);\n'
    + 'alter table sync_private.contracts enable row level security;\n' },
  { dir: 'v2', output: '202609170018_contract_v2_puzzle_optional.sql', suffix: '-v2', prologue: '', onConflict: true },
];
for (const { dir, output, suffix, prologue, onConflict } of versions) {
  let sql = '-- Generated by scripts/build-contract.mjs from protocol/' + dir + '; do not edit.\n' + prologue;
  for (const name of ['cloud-state', 'operation']) {
    const schema = JSON.parse(readFileSync(new URL('protocol/' + dir + '/' + name + '.schema.json', root), 'utf8'));
    checkContract(schema,schema);
    sql += "insert into sync_private.contracts values ('" + name + suffix + "', $contract$"
      + JSON.stringify(schema) + "$contract$::jsonb)"
      + (onConflict ? ' on conflict (name) do update set schema = excluded.schema' : '') + ';\n';
  }
  const target = new URL('migrations/' + output, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== sql) throw new Error('Contract migration is stale: ' + output);
  } else {
    writeFileSync(fileURLToPath(target), sql);
  }
}
